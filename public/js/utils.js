/**
 * StockCell - Utilitários Frontend
 */
const Utils = {
    /**
     * Formata valor em Reais
     */
    formatCurrency(value) {
        if (value == null || isNaN(value)) return 'R$ 0,00';
        return new Intl.NumberFormat('pt-BR', { style: 'currency', currency: 'BRL' }).format(value);
    },

    /**
     * Formata data para padrão BR
     */
    formatDate(dateStr) {
        if (!dateStr) return '-';
        return new Date(dateStr).toLocaleDateString('pt-BR');
    },

    /**
     * Formata data e hora
     */
    formatDateTime(dateStr) {
        if (!dateStr) return '-';
        return new Date(dateStr).toLocaleString('pt-BR', {
            day: '2-digit', month: '2-digit', year: 'numeric',
            hour: '2-digit', minute: '2-digit'
        });
    },

    /**
     * Formata apenas hora
     */
    formatTime(dateStr) {
        if (!dateStr) return '-';
        return new Date(dateStr).toLocaleString('pt-BR', { hour: '2-digit', minute: '2-digit' });
    },

    /**
     * Formata CPF
     */
    formatCPF(cpf) {
        if (!cpf) return '';
        const c = cpf.replace(/\D/g, '');
        return c.replace(/(\d{3})(\d{3})(\d{3})(\d{2})/, '$1.$2.$3-$4');
    },

    /**
     * Formata telefone
     */
    formatPhone(phone) {
        if (!phone) return '';
        const c = phone.replace(/\D/g, '');
        if (c.length === 11) return c.replace(/(\d{2})(\d{5})(\d{4})/, '($1) $2-$3');
        if (c.length === 10) return c.replace(/(\d{2})(\d{4})(\d{4})/, '($1) $2-$3');
        return phone;
    },

    /**
     * Gera um hash SHA-256 para salvar e validar senhas offline.
     * Retorna uma Promise resolvida com o hash em hexadecimal.
     */
    async hashPassword(password) {
        // Hash simples garantido para funcionar em qualquer contexto (HTTP ou HTTPS)
        let hash = 0;
        const str = String(password);
        for (let i = 0; i < str.length; i++) {
            const char = str.charCodeAt(i);
            hash = ((hash << 5) - hash) + char;
            hash = hash & hash; // 32bit integer
        }
        return 'local_' + Math.abs(hash).toString(16);
    },

    /**
     * Formata número de pedido (sequencial progressivo)
     */
    formatOrder(id, dateStr) {
        return `#${String(id).padStart(5, '0')}`;
    },

    /**
     * Debounce
     */
    debounce(fn, delay = 300) {
        let timer;
        return (...args) => {
            clearTimeout(timer);
            timer = setTimeout(() => fn(...args), delay);
        };
    },

    /**
     * Escapa HTML para prevenir XSS
     */
    escapeHTML(str) {
        if (!str) return '';
        const div = document.createElement('div');
        div.textContent = str;
        return div.innerHTML;
    },

    /**
     * Retorna a data e hora local no formato YYYY-MM-DD HH:mm:ss
     */
    getLocalISOTime() {
        const d = new Date();
        const pad = n => String(n).padStart(2, '0');
        return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
    },

    /**
     * Gera ID único
     */
    uid() {
        return Date.now().toString(36) + Math.random().toString(36).substr(2);
    },

    /**
     * Gera um UUID v4 (seguro para HTTP e conexões via IP local)
     */
    generateUUID() {
        if (typeof crypto !== 'undefined' && crypto.randomUUID) {
            return crypto.randomUUID();
        }
        return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, function(c) {
            const r = Math.random() * 16 | 0, v = c === 'x' ? r : (r & 0x3 | 0x8);
            return v.toString(16);
        });
    },

    /**
     * Máscara de input
     */
    maskInput(input, mask) {
        input.addEventListener('input', (e) => {
            let value = e.target.value.replace(/\D/g, '');
            let result = '';
            let valueIndex = 0;

            for (let i = 0; i < mask.length && valueIndex < value.length; i++) {
                if (mask[i] === '9') {
                    result += value[valueIndex++];
                } else {
                    result += mask[i];
                    if (value[valueIndex] === mask[i]) valueIndex++;
                }
            }
            e.target.value = result;
        });
    },

    /**
     * Exporta array de objetos para CSV
     */
    exportToCSV(data, filename) {
        if (!data || !data.length) {
            console.warn('Sem dados para exportar');
            return;
        }

        // Pega os headers do primeiro objeto
        const headers = Object.keys(data[0]);
        
        // Monta o CSV
        let csvContent = headers.join(';') + '\n';
        
        data.forEach(row => {
            const values = headers.map(header => {
                let val = row[header];
                if (val === null || val === undefined) val = '';
                // Se for string, escapa aspas duplas e envolve em aspas
                if (typeof val === 'string') {
                    val = val.replace(/"/g, '""');
                    return `"${val}"`;
                }
                return val;
            });
            csvContent += values.join(';') + '\n';
        });

        // Cria o blob e o link para download (com BOM para excel entender UTF-8)
        const blob = new Blob(['\ufeff' + csvContent], { type: 'text/csv;charset=utf-8;' });
        const link = document.createElement('a');
        const url = URL.createObjectURL(blob);
        
        link.setAttribute('href', url);
        link.setAttribute('download', filename.endsWith('.csv') ? filename : filename + '.csv');
        link.style.visibility = 'hidden';
        
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
        URL.revokeObjectURL(url);
    }
};

window.Utils = Utils;

